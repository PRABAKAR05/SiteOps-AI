from io import BytesIO

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

INK = colors.HexColor("#1F2937")
MUTED = colors.HexColor("#6B7280")
ACCENT = colors.HexColor("#0F766E")
LINE = colors.HexColor("#E5E7EB")

_styles = getSampleStyleSheet()
H1 = ParagraphStyle("H1", parent=_styles["Title"], fontSize=18, leading=22, textColor=INK, alignment=0, spaceAfter=2)
H2 = ParagraphStyle("H2", parent=_styles["Heading2"], fontSize=11, leading=14, textColor=ACCENT, spaceBefore=10, spaceAfter=4)
BODY = ParagraphStyle("Body", parent=_styles["BodyText"], fontSize=9.5, leading=13, textColor=INK)
SMALL = ParagraphStyle("Small", parent=_styles["BodyText"], fontSize=8, leading=11, textColor=MUTED)


def _meta_table(rows: list[tuple[str, str]]) -> Table:
    table = Table([[Paragraph(f"<b>{k}</b>", SMALL), Paragraph(v or "—", BODY)] for k, v in rows], colWidths=[38 * mm, 125 * mm])
    table.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 2),
        ("TOPPADDING", (0, 0), (-1, -1), 2),
        ("LINEBELOW", (0, 0), (-1, -1), 0.25, LINE),
    ]))
    return table


def _bullets(items: list[str]) -> list:
    if not items:
        return [Paragraph("—", BODY)]
    return [Paragraph(f"• {item}", BODY) for item in items]


def report_pdf(report: dict, project: dict, author_name: str, approver_name: str | None) -> bytes:
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=16 * mm)
    workers = report.get("workers_present") or {}
    trades = ", ".join(f"{t['trade']}: {t['count']}" for t in workers.get("by_trade", [])) or "—"
    story = [
        Paragraph("Daily Site Report", H1),
        Paragraph(f"{project['name']} · {project['code']}", SMALL),
        Spacer(1, 6),
        _meta_table([
            ("Date", report.get("report_date")),
            ("Location", report.get("location")),
            ("Submitted by", author_name),
            ("Status", (report.get("status") or "").title()),
            ("Approved by", approver_name or "Pending"),
            ("Workers present", f"{workers.get('total') or 0} ({trades})"),
        ]),
        Paragraph("Activities", H2),
        Paragraph(report.get("activities") or "—", BODY),
        Paragraph("Work completed", H2),
        *_bullets(report.get("work_completed") or []),
        Paragraph("Work pending", H2),
        *_bullets(report.get("work_pending") or []),
        Paragraph("Delays", H2),
        Paragraph(report.get("delays") or "None reported", BODY),
        Paragraph("Safety observations", H2),
        Paragraph(report.get("safety_observations") or "None reported", BODY),
        Paragraph("Materials consumed", H2),
    ]
    materials = report.get("materials_consumed") or []
    if materials:
        rows = [["Material", "Quantity", "Unit"]] + [
            [m.get("name", ""), str(m.get("quantity", "")), m.get("unit", "")] for m in materials
        ]
        table = Table(rows, colWidths=[95 * mm, 30 * mm, 25 * mm])
        table.setStyle(TableStyle([
            ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#F3F4F6")),
            ("FONTSIZE", (0, 0), (-1, -1), 8.5),
            ("GRID", (0, 0), (-1, -1), 0.25, LINE),
            ("ALIGN", (1, 1), (-1, -1), "RIGHT"),
        ]))
        story.append(table)
    else:
        story.append(Paragraph("None recorded", BODY))

    if report.get("ai_summary"):
        story += [Paragraph("AI-assisted summary", H2), Paragraph(report["ai_summary"], BODY)]
    if report.get("notes"):
        story += [Paragraph("Notes", H2), Paragraph(report["notes"], BODY)]
    story += [Spacer(1, 10), Paragraph("Generated by SiteOps AI · demo data unless stated otherwise", SMALL)]
    doc.build(story)
    return buf.getvalue()


def period_pdf(project: dict, stats: dict, date_from: str, date_to: str, summary: str | None) -> bytes:
    buf = BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=18 * mm, rightMargin=18 * mm, topMargin=16 * mm, bottomMargin=16 * mm)
    rows = [[k.replace("_", " ").title(), str(v)] for k, v in stats.items()]
    table = Table(rows, colWidths=[80 * mm, 60 * mm])
    table.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("GRID", (0, 0), (-1, -1), 0.25, LINE),
        ("BACKGROUND", (0, 0), (0, -1), colors.HexColor("#F9FAFB")),
    ]))
    story = [
        Paragraph("Project Period Summary", H1),
        Paragraph(f"{project['name']} · {date_from} to {date_to}", SMALL),
        Spacer(1, 8),
        table,
        Paragraph("Summary", H2),
        Paragraph(summary or "No narrative summary was generated for this period.", BODY),
        Spacer(1, 10),
        Paragraph("Numbers are computed from site records. Narrative text, when present, is AI-assisted and labeled.", SMALL),
    ]
    doc.build(story)
    return buf.getvalue()
